            "# Early Stopping Manager for CycleGAN\n",
            "class CycleGANValidator:\n",
            "    def __init__(self, patience=8, min_delta=1e-4, ckpt_dir=None):\n",
            "        self.patience = patience\n",
            "        self.min_delta = min_delta\n",
            "        self.ckpt_dir = Path(ckpt_dir) if ckpt_dir else None\n",
            "        if self.ckpt_dir:\n",
            "            self.ckpt_dir.mkdir(parents=True, exist_ok=True)\n",
            "        self.best_loss = float('inf')\n",
            "        self.best_epoch = 0\n",
            "        self.counter = 0\n",
            "        self.early_stop = False\n",
            "        self.history = []\n",
            "\n",
            "    def step(self, epoch, loss_G, loss_cycle, loss_D, G_AB, G_BA, domain_name):\n",
            "        self.history.append({\n",
            "            'epoch': epoch,\n",
            "            'loss_G': float(loss_G),\n",
            "            'loss_cycle': float(loss_cycle),\n",
            "            'loss_D': float(loss_D)\n",
            "        })\n",
            "        improved = False\n",
            "        if loss_G < self.best_loss - self.min_delta:\n",
            "            self.best_loss = loss_G\n",
            "            self.best_epoch = epoch\n",
            "            self.counter = 0\n",
            "            improved = True\n",
            "            self.save_checkpoint(epoch, loss_G, loss_cycle, G_AB, G_BA, domain_name, is_best=True)\n",
            "        else:\n",
            "            self.counter += 1\n",
            "            if self.counter >= self.patience:\n",
            "                self.early_stop = True\n",
            "                print(f'\\n[EARLY STOPPING TRIGGERED] Loss did not improve for {self.patience} epochs. Best epoch was {self.best_epoch} with loss_G {self.best_loss:.4f}')\n",
            "        self.save_checkpoint(epoch, loss_G, loss_cycle, G_AB, G_BA, domain_name, is_best=False)\n",
            "        return improved\n",
            "\n",
            "    def save_checkpoint(self, epoch, loss_G, loss_cycle, G_AB, G_BA, domain_name, is_best=False):\n",
            "        if not self.ckpt_dir:\n",
            "            return\n",
            "        state = {\n",
            "            'epoch': epoch,\n",
            "            'generator': G_AB.state_dict(),\n",
            "            'generator_state_dict': G_AB.state_dict(),\n",
            "            'netG': G_AB.state_dict(),\n",
            "            'G_A': G_AB.state_dict(),\n",
            "            'G_AB_state_dict': G_AB.state_dict(),\n",
            "            'G_BA_state_dict': G_BA.state_dict(),\n",
            "            'loss_G': float(loss_G),\n",
            "            'loss_cycle': float(loss_cycle),\n",
            "            'domain': domain_name,\n",
            "            'target': 'Fog'\n",
            "        }\n",
            "        final_path = self.ckpt_dir / 'checkpoint_final.pth'\n",
            "        torch.save(state, final_path)\n",
            "        if is_best:\n",
            "            best_path = self.ckpt_dir / 'checkpoint_best.pth'\n",
            "            torch.save(state, best_path)\n",
            "            print(f'Saved best checkpoint: {best_path}')\n",
            "print('Early stopping controller ready.')\n"
