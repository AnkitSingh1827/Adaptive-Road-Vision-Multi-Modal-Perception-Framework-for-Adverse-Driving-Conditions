            "# In-Memory Cached Unpaired CycleGAN Dataset Definition\n",
            "class CachedCycleGANDataset(Dataset):\n",
            "    def __init__(self, domain_a_paths, domain_b_paths, img_size=256, is_train=True):\n",
            "        self.domain_a_paths = list(domain_a_paths)\n",
            "        self.domain_b_paths = list(domain_b_paths)\n",
            "        self.is_train = is_train\n",
            "        transform = transforms.Compose([\n",
            "            transforms.Resize((img_size, img_size), interpolation=transforms.InterpolationMode.BICUBIC),\n",
            "            transforms.ToTensor(),\n",
            "            transforms.Normalize((0.5, 0.5, 0.5), (0.5, 0.5, 0.5))\n",
            "        ])\n",
            "        print(f\"Pre-caching {len(self.domain_a_paths)} sources and {len(self.domain_b_paths)} fog images into RAM...\")\n",
            "        self.tensors_a = []\n",
            "        for p in self.domain_a_paths:\n",
            "            with Image.open(p) as img:\n",
            "                self.tensors_a.append(transform(img.convert('RGB')))\n",
            "        self.tensors_b = []\n",
            "        for p in self.domain_b_paths:\n",
            "            with Image.open(p) as img:\n",
            "                self.tensors_b.append(transform(img.convert('RGB')))\n",
            "        print(f\"Pre-caching complete ({len(self.tensors_a)} A, {len(self.tensors_b)} B).\")\n",
            "\n",
            "    def __len__(self):\n",
            "        return max(len(self.tensors_a), len(self.tensors_b))\n",
            "\n",
            "    def __getitem__(self, idx):\n",
            "        a = self.tensors_a[idx % len(self.tensors_a)]\n",
