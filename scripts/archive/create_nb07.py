            "# Model Architectures (strictly matching Notebook 08 ResnetGenerator)\n",
            "class ResnetBlock(nn.Module):\n",
            "    def __init__(self, dim):\n",
            "        super().__init__()\n",
            "        self.block = nn.Sequential(\n",
            "            nn.ReflectionPad2d(1),\n",
            "            nn.Conv2d(dim, dim, 3, padding=0, bias=True),\n",
            "            nn.InstanceNorm2d(dim),\n",
            "            nn.ReLU(True),\n",
            "            nn.ReflectionPad2d(1),\n",
            "            nn.Conv2d(dim, dim, 3, padding=0, bias=True),\n",
            "            nn.InstanceNorm2d(dim),\n",
            "        )\n",
            "    def forward(self, x):\n",
            "        return x + self.block(x)\n",
            "\n",
            "class ResnetGenerator(nn.Module):\n",
            "    def __init__(self, input_nc=3, output_nc=3, ngf=64, n_blocks=6):\n",
            "        super().__init__()\n",
            "        layers = [\n",
            "            nn.ReflectionPad2d(3),\n",
            "            nn.Conv2d(input_nc, ngf, 7, padding=0),\n",
            "            nn.InstanceNorm2d(ngf),\n",
            "            nn.ReLU(True),\n",
            "        ]\n",
            "        mult = 1\n",
            "        for _ in range(2):\n",
            "            layers += [\n",
            "                nn.Conv2d(ngf * mult, ngf * mult * 2, 3, stride=2, padding=1),\n",
            "                nn.InstanceNorm2d(ngf * mult * 2),\n",
            "                nn.ReLU(True),\n",
            "            ]\n",
            "            mult *= 2\n",
            "        for _ in range(n_blocks):\n",
            "            layers.append(ResnetBlock(ngf * mult))\n",
            "        for _ in range(2):\n",
            "            layers += [\n",
            "                nn.ConvTranspose2d(ngf * mult, ngf * mult // 2, 3, stride=2, padding=1, output_padding=1),\n",
            "                nn.InstanceNorm2d(ngf * mult // 2),\n",
            "                nn.ReLU(True),\n",
            "            ]\n",
            "            mult //= 2\n",
            "        layers += [\n",
            "            nn.ReflectionPad2d(3),\n",
            "            nn.Conv2d(ngf, output_nc, 7, padding=0),\n",
            "            nn.Tanh(),\n",
            "        ]\n",
            "        self.model = nn.Sequential(*layers)\n",
            "    def forward(self, x):\n",
            "        return self.model(x)\n",
            "\n",
            "class PatchGANDiscriminator(nn.Module):\n",
            "    def __init__(self, input_nc=3, ndf=64):\n",
            "        super().__init__()\n",
            "        self.model = nn.Sequential(\n",
            "            nn.Conv2d(input_nc, ndf, 4, stride=2, padding=1),\n",
            "            nn.LeakyReLU(0.2, True),\n",
            "            nn.Conv2d(ndf, ndf * 2, 4, stride=2, padding=1, bias=False),\n",
            "            nn.InstanceNorm2d(ndf * 2),\n",
            "            nn.LeakyReLU(0.2, True),\n",
            "            nn.Conv2d(ndf * 2, ndf * 4, 4, stride=2, padding=1, bias=False),\n",
            "            nn.InstanceNorm2d(ndf * 4),\n",
            "            nn.LeakyReLU(0.2, True),\n",
            "            nn.Conv2d(ndf * 4, ndf * 8, 4, stride=1, padding=1, bias=False),\n",
            "            nn.InstanceNorm2d(ndf * 8),\n",
            "            nn.LeakyReLU(0.2, True),\n",
            "            nn.Conv2d(ndf * 8, 1, 4, stride=1, padding=1)\n",
            "        )\n",
            "    def forward(self, x):\n",
            "        return self.model(x)\n",
            "print('Generator and Discriminator architectures initialized.')\n"
