            "# Optimized High-Throughput Training Engine\n",
            "def train_cyclegan_model(domain_name, source_paths, fog_paths, epochs=60, batch_size=4, lr=2e-4, patience=8, max_train_samples=250):\n",
            "    print('=' * 70)\n",
            "    print(f'TRAINING CYCLEGAN: {domain_name.upper()} -> FOG')\n",
            "    print(f'Epochs: {epochs} | Early Stopping Patience: {patience} | Device: {DEVICE}')\n",
            "    print('=' * 70)\n",
            "    ckpt_dir = MODELS_DIR / f'{domain_name.lower()}_to_fog'\n",
            "    ckpt_dir.mkdir(parents=True, exist_ok=True)\n",
            "    \n",
            "    train_sources = source_paths[:max_train_samples] if max_train_samples else source_paths\n",
            "    dataset = CachedCycleGANDataset(train_sources, fog_paths, img_size=256, is_train=True)\n",
            "    loader = DataLoader(dataset, batch_size=batch_size, shuffle=True, drop_last=True)\n",
            "    \n",
            "    G_AB = ResnetGenerator().to(DEVICE)\n",
            "    G_BA = ResnetGenerator().to(DEVICE)\n",
            "    D_A = PatchGANDiscriminator().to(DEVICE)\n",
            "    D_B = PatchGANDiscriminator().to(DEVICE)\n",
            "    \n",
            "    criterion_GAN = nn.MSELoss()\n",
            "    criterion_cycle = nn.L1Loss()\n",
            "    criterion_identity = nn.L1Loss()\n",
            "    \n",
            "    optimizer_G = torch.optim.Adam(list(G_AB.parameters()) + list(G_BA.parameters()), lr=lr, betas=(0.5, 0.999))\n",
            "    optimizer_D = torch.optim.Adam(list(D_A.parameters()) + list(D_B.parameters()), lr=lr, betas=(0.5, 0.999))\n",
            "    scaler = torch.amp.GradScaler('cuda') if DEVICE.type == 'cuda' else None\n",
            "    \n",
            "    early_stopper = CycleGANValidator(patience=patience, min_delta=1e-4, ckpt_dir=ckpt_dir)\n",
            "    \n",
            "    for epoch in range(1, epochs + 1):\n",
            "        G_AB.train()\n",
            "        G_BA.train()\n",
            "        D_A.train()\n",
            "        D_B.train()\n",
            "        \n",
            "        total_loss_G = 0.0\n",
            "        total_loss_cycle = 0.0\n",
            "        total_loss_D = 0.0\n",
            "        start_t = time.time()\n",
            "        \n",
            "        for i, batch in enumerate(loader):\n",
            "            real_A = batch['A'].to(DEVICE, non_blocking=True)\n",
            "            real_B = batch['B'].to(DEVICE, non_blocking=True)\n",
            "            \n",
            "            optimizer_G.zero_grad()\n",
            "            with torch.amp.autocast('cuda', enabled=(DEVICE.type == 'cuda')):\n",
            "                loss_id_A = criterion_identity(G_BA(real_A), real_A) * 5.0\n",
            "                loss_id_B = criterion_identity(G_AB(real_B), real_B) * 5.0\n",
            "                loss_identity = (loss_id_A + loss_id_B) / 2.0\n",
            "                \n",
            "                fake_B = G_AB(real_A)\n",
            "                pred_fake_B = D_B(fake_B)\n",
            "                target_real = torch.ones_like(pred_fake_B)\n",
            "                target_fake = torch.zeros_like(pred_fake_B)\n",
            "                loss_GAN_AB = criterion_GAN(pred_fake_B, target_real)\n",
            "                \n",
            "                fake_A = G_BA(real_B)\n",
            "                pred_fake_A = D_A(fake_A)\n",
            "                loss_GAN_BA = criterion_GAN(pred_fake_A, target_real)\n",
            "                loss_GAN = (loss_GAN_AB + loss_GAN_BA) / 2.0\n",
            "                \n",
            "                recov_A = G_BA(fake_B)\n",
            "                loss_cycle_A = criterion_cycle(recov_A, real_A) * 10.0\n",
            "                recov_B = G_AB(fake_A)\n",
            "                loss_cycle_B = criterion_cycle(recov_B, real_B) * 10.0\n",
            "                loss_cycle = (loss_cycle_A + loss_cycle_B) / 2.0\n",
            "                \n",
            "                loss_G = loss_GAN + loss_cycle + loss_identity\n",
            "            \n",
            "            if scaler:\n",
            "                scaler.scale(loss_G).backward()\n",
            "                scaler.step(optimizer_G)\n",
            "                scaler.update()\n",
            "            else:\n",
            "                loss_G.backward()\n",
            "                optimizer_G.step()\n",
            "            \n",
            "            optimizer_D.zero_grad()\n",
            "            with torch.amp.autocast('cuda', enabled=(DEVICE.type == 'cuda')):\n",
            "                loss_real_A = criterion_GAN(D_A(real_A), target_real)\n",
            "                loss_fake_A = criterion_GAN(D_A(fake_A.detach()), target_fake)\n",
            "                loss_D_A = (loss_real_A + loss_fake_A) / 2.0\n",
            "                \n",
            "                loss_real_B = criterion_GAN(D_B(real_B), target_real)\n",
            "                loss_fake_B = criterion_GAN(D_B(fake_B.detach()), target_fake)\n",
            "                loss_D_B = (loss_real_B + loss_fake_B) / 2.0\n",
            "                loss_D = (loss_D_A + loss_D_B) / 2.0\n",
            "            \n",
            "            if scaler:\n",
            "                scaler.scale(loss_D).backward()\n",
            "                scaler.step(optimizer_D)\n",
            "                scaler.update()\n",
            "            else:\n",
            "                loss_D.backward()\n",
            "                optimizer_D.step()\n",
            "            \n",
            "            total_loss_G += loss_G.item()\n",
            "            total_loss_cycle += loss_cycle.item()\n",
            "            total_loss_D += loss_D.item()\n",
            "        \n",
            "        avg_G = total_loss_G / len(loader)\n",
            "        avg_cycle = total_loss_cycle / len(loader)\n",
            "        avg_D = total_loss_D / len(loader)\n",
            "        elapsed = time.time() - start_t\n",
            "        \n",
            "        print(f'Epoch [{epoch:02d}/{epochs:02d}] {elapsed:.1f}s | G Loss: {avg_G:.4f} (Cycle: {avg_cycle:.4f}) | D Loss: {avg_D:.4f}')\n",
            "        early_stopper.step(epoch, avg_G, avg_cycle, avg_D, G_AB, G_BA, domain_name)\n",
            "        \n",
            "        if early_stopper.early_stop:\n",
            "            print(f'Stopping early at epoch {epoch}. Model converged successfully.')\n",
            "            break\n",
            "            \n",
            "    history_file = RESULTS_DIR / f'cyclegan_{domain_name.lower()}_to_fog_history.json'\n",
            "    with open(history_file, 'w', encoding='utf-8') as f:\n",
            "        json.dump(early_stopper.history, f, indent=2)\n",
            "    print(f'Saved training history to {history_file}')\n",
            "    return ckpt_dir / 'checkpoint_final.pth'\n",
            "print('Training function compiled.')\n"
